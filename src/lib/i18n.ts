export type I18nKey = keyof typeof messages.en;

export function translate(
  language: LanguageMode,
  key: I18nKey,
  values?: Record<string, string | number>,
): string {
  const template: string = messages[language][key] ?? messages.en[key] ?? key;
  if (!values) return template;

  return Object.entries(values).reduce(
    (result, [name, value]) => result.split(`{${name}}`).join(String(value)),
    template,
  );
}

export function translatedLogLevel(language: LanguageMode, level: LogLevel) {
  return translate(language, `logs.${level}` as I18nKey);
}

export function useI18n() {
  const { language } = useFileKit();
  const t = useCallback(
    (key: I18nKey, values?: Record<string, string | number>) =>
      translate(language, key, values),
    [language],
  );

  return { language, t };
}
